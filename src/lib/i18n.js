export function t(value, lang) {
  if (lang !== "ru" || typeof value !== "string") return value;
  return ru[value] || value;
}

export function translateTree(value, lang) {
  if (Array.isArray(value)) return value.map((item) => translateTree(item, lang));
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, translateTree(item, lang)])
    );
  }
  return t(value, lang);
}
